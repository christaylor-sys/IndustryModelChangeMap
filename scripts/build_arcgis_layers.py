"""Build ArcGIS-ready spatial layers directly from data/processed/*.parquet.

Reads:
  - data/processed/ep_long.parquet
  - data/processed/dim_geography.parquet
  - data/processed/dim_slices.parquet

Writes:
  - data/processed/arcgis_county_ep.gpkg (GeoPackage for ArcGIS Pro / QGIS)
  - data/processed/arcgis_all_perils_all_lobs.geojson (GeoJSON for ArcGIS Online)

Usage:
  python scripts/build_arcgis_layers.py
  python scripts/build_arcgis_layers.py --peril ALL --lob ALL
"""
from __future__ import annotations

import argparse
import logging
import urllib.parse
import urllib.request
from pathlib import Path

import numpy as np
import pandas as pd

log = logging.getLogger("arcgis_export")

LIVING_ATLAS_QUERY_URL = (
    "https://services.arcgis.com/P3ePLMYs2RVChkJx/arcgis/rest/services/"
    "USA_Counties_Generalized_Boundaries/FeatureServer/0/query"
)


def load_parquet_tables(processed_dir: Path) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Load the three Parquet outputs generated by run_pipeline.py."""
    long_df = pd.read_parquet(processed_dir / "ep_long.parquet")
    geo_df = pd.read_parquet(processed_dir / "dim_geography.parquet")
    slices_df = pd.read_parquet(processed_dir / "dim_slices.parquet")
    return long_df, geo_df, slices_df


def pivot_slice_wide(
    long_df: pd.DataFrame,
    geo_df: pd.DataFrame,
    model_code: str = "ALL",
    peril: str = "ALL",
    lob_code: str = "ALL",
    old_col: str = "v12",
    new_col: str = "v13",
) -> pd.DataFrame:
    """Pivot ep_long.parquet for a (model, peril, lob) slice into a wide county table
    with recomputed DIFF and PCT_DIFF metrics."""
    sub = long_df[
        (long_df["model_code"] == model_code)
        & (long_df["peril"] == peril)
        & (long_df["lob_code"] == lob_code)
    ].copy()

    if sub.empty:
        raise ValueError(f"No rows found for model={model_code}, peril={peril}, lob={lob_code}")

    sub["metric_key"] = np.where(
        sub["curve"].astype(str) == "AAL",
        "AAL",
        sub["curve"].astype(str) + "_" + sub["return_period"].astype(str),
    )

    old_wide = sub.pivot(index="fips", columns="metric_key", values=old_col).add_prefix(f"{old_col.upper()}_")
    new_wide = sub.pivot(index="fips", columns="metric_key", values=new_col).add_prefix(f"{new_col.upper()}_")

    wide = old_wide.join(new_wide, how="outer").reset_index()

    # Recompute DIFF and PCT_DIFF columns (dropped in ep_long.parquet by design)
    for m in sub["metric_key"].unique():
        c_old = f"{old_col.upper()}_{m}"
        c_new = f"{new_col.upper()}_{m}"
        wide[f"DIFF_{m}"] = wide[c_new] - wide[c_old]
        wide[f"PCT_{m}"] = np.where(
            wide[c_old] > 1.0, (wide[c_new] - wide[c_old]) / wide[c_old] * 100.0, np.nan
        )

    return geo_df.merge(wide, on="fips", how="inner")


def fetch_esri_county_geojson(cache_path: Path) -> Path:
    """Download US County generalized boundaries from Esri Living Atlas as GeoJSON."""
    if cache_path.exists():
        return cache_path

    log.info("Downloading US County boundaries from Esri Living Atlas...")
    params = urllib.parse.urlencode({
        "where": "1=1",
        "outFields": "FIPS,NAME,STATE_NAME,STATE_ABBR",
        "outSR": "4326",
        "f": "geojson",
    })
    url = f"{LIVING_ATLAS_QUERY_URL}?{params}"
    cache_path.parent.mkdir(parents=True, exist_ok=True)
    urllib.request.urlretrieve(url, cache_path)
    return cache_path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--processed-dir", type=Path, default=Path("data/processed"))
    parser.add_argument("--model", default="ALL")
    parser.add_argument("--peril", default="ALL")
    parser.add_argument("--lob", default="ALL")
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(levelname)-7s %(message)s")

    long_df, geo_df, slices_df = load_parquet_tables(args.processed_dir)
    log.info(
        "Loaded ep_long.parquet (%s rows), dim_geography (%s counties), dim_slices (%s slices)",
        f"{len(long_df):,}", f"{len(geo_df):,}", f"{len(slices_df):,}"
    )

    wide_df = pivot_slice_wide(
        long_df, geo_df,
        model_code=args.model, peril=args.peril, lob_code=args.lob
    )

    # Always write a clean CSV with lat/lon and FIPS that ArcGIS Pro / Online can join immediately
    csv_out = args.processed_dir / f"arcgis_slice_{args.model}_{args.peril}_{args.lob}.csv"
    wide_df.to_csv(csv_out, index=False)
    log.info("Wrote ArcGIS-ready attribute & centroid table to %s", csv_out)

    # If geopandas is installed, also build a polygon GeoPackage & GeoJSON joined to Esri Living Atlas
    try:
        import geopandas as gpd

        boundaries_path = fetch_esri_county_geojson(args.processed_dir / "esri_counties_cache.geojson")
        counties_gdf = gpd.read_file(boundaries_path)[["FIPS", "geometry"]].rename(columns={"FIPS": "fips"})

        merged_gdf = counties_gdf.merge(wide_df, on="fips", how="inner")
        geojson_out = args.processed_dir / f"arcgis_slice_{args.model}_{args.peril}_{args.lob}.geojson"
        gpkg_out = args.processed_dir / "arcgis_county_ep.gpkg"

        merged_gdf.to_file(geojson_out, driver="GeoJSON")
        merged_gdf.to_file(gpkg_out, layer=f"ep_{args.model}_{args.peril}_{args.lob}", driver="GPKG")
        log.info("Wrote spatial polygon layers to %s and %s", geojson_out, gpkg_out)
    except ImportError:
        log.info("Install 'geopandas' (pip install geopandas) to also export pre-joined .gpkg/.geojson polygons.")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
